export const MESSAGES: Record<Language, Record<MessageKey, string>> = { ja, en };

/** Japanese for a Japanese locale, English otherwise, as the apps choose. */
export function detectLanguage(environment: NodeJS.ProcessEnv): Language {
  const locale = environment.LC_ALL || environment.LC_MESSAGES || environment.LANG || '';
  return /^ja(?:[_.-]|$)/i.test(locale) ? 'ja' : 'en';
}

export type Translate = (key: MessageKey, values?: Record<string, string | number>) => string;

export function translator(language: Language): Translate {
  const messages = MESSAGES[language];
  return (key, values = {}) => messages[key].replace(/\{(\w+)\}/g, (match, name: string) => (name in values ? String(values[name]) : match));
}
