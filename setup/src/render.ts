// The files the setup generates. compose.production.yml stays the definition
// of the hardened app and migrator; compose.json adds what it leaves to the
// operator: PostgreSQL and the object store, both behind TLS from a private
// authority, the HTTPS proxy, the voice relay, and the backup tools.

export const GENERATED_HEADER = 'Generated by the Alparts setup (setup/alparts-setup). Changes are replaced on its next run.';

const LOGGING = { driver: 'json-file', options: { 'max-size': '10m', 'max-file': '5' } } as const;

/** Values in single quotes are taken literally by Compose: no `$` interpolation. */
export function renderEnvFile(values: Record<string, string>): string {
  const lines = [`# ${GENERATED_HEADER}`];
  for (const [key, value] of Object.entries(values)) {
    if (!/^[A-Z][A-Z0-9_]*$/.test(key) || /['\r\n]/.test(value)) throw new Error(`Cannot write ${key} to an env file`);
    lines.push(`${key}='${value}'`);
  }
  return `${lines.join('\n')}\n`;
}

export function composeEnvironment(settings: Settings, paths: Paths, imageTag: string): Record<string, string> {
  const secret = (name: SecretName) => join(paths.secretsDir, name);
  const email = settings.email;
  const cpus = Math.min(2, availableParallelism());
  return {
    ALPARTS_IMAGE_TAG: imageTag,
    ALPARTS_HOST_PORT: String(settings.network.appPort),
    // compose.production.yml asks for 2 CPUs by default, which a 1-CPU host refuses.
    ALPARTS_CPU_LIMIT: cpus.toFixed(1),
    DB_SSL: 'true',
    S3_ENDPOINT: STORAGE.host,
    S3_PORT: String(STORAGE.port),
    S3_USE_SSL: 'true',
    S3_REGION: 'us-east-1',
    S3_BUCKET: STORAGE.bucket,
    AUDIT_HEAD_BUCKET: STORAGE.auditBucket,
    AUDIT_HEAD_OBJECT_KEY: settings.auditHeadObjectKey,
    AUDIT_WITNESS_REQUIRED: 'false',
    AUDIT_WITNESS_DIR: paths.emptyDir,
    CORS_ORIGINS: `https://${settings.domain}`,
    TRUSTED_PROXIES: edgeNetworkLayout(settings.network.edgeSubnet).proxyAddress,
    EMAIL_VERIFICATION: email.mode === 'smtp' ? 'required' : 'disabled',
    SMTP_HOST: email.mode === 'smtp' ? email.host : '',
    SMTP_PORT: email.mode === 'smtp' ? String(email.port) : '587',
    SMTP_SECURE: email.mode === 'smtp' && email.security === 'tls' ? 'true' : 'false',
    SMTP_FROM: email.mode === 'smtp' ? email.from : '',
    SMTP_USER: email.mode === 'smtp' ? email.user ?? '' : '',
    ALLOW_INSECURE_LOOPBACK_DEPENDENCIES: 'false',
    METRICS_ENABLED: 'false',
    DATABASE_URL_SECRET_FILE: secret('database_url'),
    MIGRATION_DATABASE_URL_SECRET_FILE: secret('migration_database_url'),
    S3_ACCESS_KEY_SECRET_FILE: secret('storage_app_access_key'),
    S3_SECRET_KEY_SECRET_FILE: secret('storage_app_secret_key'),
    JWT_SECRET_SECRET_FILE: secret('jwt_secret'),
    PASSWORD_PEPPER_SECRET_FILE: secret('password_pepper'),
    PASSWORD_PEPPER_PREVIOUS_SECRET_FILE: secret('empty'),
    AUDIT_INTEGRITY_KEY_SECRET_FILE: secret('audit_integrity_key'),
    METRICS_TOKEN_SECRET_FILE: secret('empty'),
    SMTP_PASSWORD_SECRET_FILE: secret('smtp_password'),
  };
}

/** The ports of the voice relay: one per media worker, the same number for UDP and TCP. */
export function voicePortRange(settings: Settings): string {
  const { basePort, workers } = settings.voice;
  return workers === 1 ? String(basePort) : `${basePort}-${basePort + workers - 1}`;
}

/**
 * The image's own start command without Node's permission model. Current Node
 * releases (checked with 22.22 and 24.22) turn off fsync under that model, and
 * the audit checkpoint is synced to disk before it replaces the old one; with
 * the model on, the first audited write fails and the app stops accepting
 * writes. The container still confines the process: a read-only root, no
 * capabilities, no new privileges, a non-root user. The other flags, such as
 * --disallow-code-generation-from-strings, stay.
 */
export function appStartCommand(imageCommand: string[]): string[] {
  return imageCommand.filter((argument) => argument !== '--permission' && !argument.startsWith('--allow-'));
}

const POSTGRES_START = [
  'set -eu',
  'umask 077',
  // Copied into a private tmpfs, owned as PostgreSQL requires for the key.
  'install -o postgres -g postgres -m 0600 /run/secrets/postgres_tls_certificate /run/alparts/server.crt',
  'install -o postgres -g postgres -m 0600 /run/secrets/postgres_tls_key /run/alparts/server.key',
  'install -o postgres -g postgres -m 0600 /etc/alparts/pg_hba.conf /run/alparts/pg_hba.conf',
  'chown postgres:postgres /run/alparts',
  'exec docker-entrypoint.sh postgres -c ssl=on -c ssl_min_protocol_version=TLSv1.2'
    + ' -c ssl_cert_file=/run/alparts/server.crt -c ssl_key_file=/run/alparts/server.key'
    + ' -c hba_file=/run/alparts/pg_hba.conf -c password_encryption=scram-sha-256',
].join('\n');

const OBJECT_STORAGE_START = [
  'set -eu',
  'umask 077',
  'cp /run/secrets/storage_identities /run/alparts/s3.json',
  'cp /run/secrets/storage_tls_certificate /run/alparts/tls.crt',
  'cp /run/secrets/storage_tls_key /run/alparts/tls.key',
  'chown -R seaweed:seaweed /run/alparts',
  // Only the S3 API serves the network, with TLS; the identities file decides who may do what.
  `exec /entrypoint.sh mini -dir=/data -s3.config=/run/alparts/s3.json -s3.cert.file=/run/alparts/tls.crt -s3.key.file=/run/alparts/tls.key`
    + ` -bucket=${STORAGE.bucket},${STORAGE.auditBucket}`
    + ' -master.telemetry=false -admin.ui=false -webdav=false -s3.iam=false -s3.port.iceberg=0 -s3.port.lance=0',
].join('\n');

export interface OverrideOptions {
  /** The app image's own command, which the app's start command is derived from. */
  appCommand: string[];
  backupImage: string;
}

export function renderComposeOverride(settings: Settings, paths: Paths, options: OverrideOptions): string {
  const layout = edgeNetworkLayout(settings.network.edgeSubnet);
  const relay = settings.voice.relay;
  const ports = voicePortRange(settings);
  const secretFile = (name: SecretName) => ({ file: join(paths.secretsDir, name) });

  const appEnvironment: Record<string, string> = {
    NODE_EXTRA_CA_CERTS: '/run/secrets/internal_ca_certificate',
    REGISTRATION_INVITE_SECRET_FILE: '/run/secrets/registration_invite_secret',
    VOICE_ICE_SERVERS_JSON: '[]',
    VOICE_SFU_ENABLED: relay ? 'true' : 'false',
  };
  if (relay) {
    Object.assign(appEnvironment, {
      VOICE_SFU_BIND_ADDRESS: '0.0.0.0',
      VOICE_SFU_ANNOUNCED_ADDRESS: settings.voice.publicAddress!,
      VOICE_SFU_BASE_PORT: String(settings.voice.basePort),
      VOICE_SFU_WORKERS: String(settings.voice.workers),
    });
  }

  const app: Record<string, unknown> = {
    command: appStartCommand(options.appCommand),
    environment: appEnvironment,
    secrets: ['internal_ca_certificate', 'registration_invite_secret'],
    networks: { edge: {}, backend: {} },
    depends_on: {
      postgres: { condition: 'service_healthy' },
      'object-storage': { condition: 'service_healthy' },
    },
    logging: LOGGING,
  };
  if (relay) {
    app.ports = [`${ports}:${ports}/udp`, `${ports}:${ports}/tcp`];
    // Keeps the container's own outgoing connections off the relay ports.
    app.sysctls = { 'net.ipv4.ip_local_reserved_ports': ports };
  }

  const override = {
    'x-alparts-setup': GENERATED_HEADER,
    services: {
      app,
      migrator: {
        environment: { NODE_EXTRA_CA_CERTS: '/run/secrets/internal_ca_certificate' },
        secrets: ['internal_ca_certificate'],
        networks: { backend: {} },
        logging: LOGGING,
      },
      postgres: {
        image: IMAGES.postgres,
        restart: 'unless-stopped',
        environment: {
          POSTGRES_USER: 'postgres',
          POSTGRES_DB: 'postgres',
          POSTGRES_PASSWORD_FILE: '/run/secrets/postgres_superuser_password',
        },
        secrets: ['postgres_superuser_password', 'postgres_tls_certificate', 'postgres_tls_key'],
        volumes: ['postgres_data:/var/lib/postgresql/data', `${paths.postgresConfigDir}:/etc/alparts:ro`],
        tmpfs: ['/run/alparts:mode=0700'],
        entrypoint: ['/bin/sh', '-c'],
        command: [POSTGRES_START],
        healthcheck: {
          // As the postgres user, which the local connection rule admits without a password.
          test: ['CMD', 'gosu', 'postgres', 'pg_isready', '-q', '-d', 'postgres'],
          interval: '5s',
          timeout: '5s',
          retries: 30,
          start_period: '60s',
        },
        stop_grace_period: '60s',
        security_opt: ['no-new-privileges:true'],
        networks: { backend: {} },
        logging: LOGGING,
      },
      'object-storage': {
        image: IMAGES.objectStorage,
        restart: 'unless-stopped',
        secrets: ['storage_identities', 'storage_tls_certificate', 'storage_tls_key'],
        volumes: ['object_storage_data:/data'],
        tmpfs: ['/run/alparts:mode=0700'],
        entrypoint: ['/bin/sh', '-c'],
        command: [OBJECT_STORAGE_START],
        healthcheck: {
          test: ['CMD-SHELL', `echo s3.bucket.list | weed shell 2>/dev/null | grep -qE '^[[:space:]]+${STORAGE.auditBucket}[[:space:]]'`],
          interval: '5s',
          timeout: '10s',
          retries: 24,
          start_period: '30s',
        },
        security_opt: ['no-new-privileges:true'],
        networks: { backend: {} },
        logging: LOGGING,
      },
      proxy: {
        image: IMAGES.proxy,
        restart: 'unless-stopped',
        ports: ['80:80/tcp', '443:443/tcp', '443:443/udp'],
        volumes: [`${paths.proxyConfigDir}:/etc/caddy:ro`, 'proxy_data:/data', 'proxy_config:/config'],
        networks: { edge: { ipv4_address: layout.proxyAddress } },
        read_only: true,
        tmpfs: ['/tmp'],
        cap_drop: ['ALL'],
        cap_add: ['NET_BIND_SERVICE'],
        security_opt: ['no-new-privileges:true'],
        logging: LOGGING,
      },
      backup: {
        image: options.backupImage,
        build: { context: join(paths.repo, 'setup', 'backup-tools') },
        profiles: ['operations'],
        restart: 'no',
        environment: {
          DATABASE_SERVICE_FILE: '/run/secrets/backup_pg_service',
          DATABASE_SERVICE: 'alparts_backup',
          S3_URL: `https://${STORAGE.host}:${STORAGE.port}`,
          S3_ACCESS_KEY_FILE: '/run/secrets/storage_backup_access_key',
          S3_SECRET_KEY_FILE: '/run/secrets/storage_backup_secret_key',
          S3_BUCKET: STORAGE.bucket,
          BACKUP_AGE_RECIPIENT_FILE: '/run/secrets/backup_age_recipient',
          BACKUP_OUTPUT_DIR: '/backups',
          BACKUP_RETENTION_DAYS: String(settings.backup?.retentionDays ?? 30),
          BACKUP_MINIMUM_COPIES: String(settings.backup?.minimumCopies ?? 7),
          // rclone trusts the private authority of the object store through this file.
          SSL_CERT_FILE: '/run/secrets/internal_ca_certificate',
          TMPDIR: '/work',
        },
        secrets: ['internal_ca_certificate', 'backup_pg_service', 'storage_backup_access_key', 'storage_backup_secret_key', 'backup_age_recipient'],
        volumes: [`${join(paths.repo, 'scripts')}:/opt/alparts/scripts:ro`, `${paths.backupDir}:/backups`, 'backup_work:/work'],
        security_opt: ['no-new-privileges:true'],
        networks: { backend: {} },
        logging: LOGGING,
      },
    },
    networks: {
      edge: { ipam: { config: [{ subnet: layout.subnet, ip_range: layout.dynamicRange, gateway: layout.gateway }] } },
      // No route out: the database and the object store talk to the app only.
      backend: { internal: true },
    },
    volumes: {
      postgres_data: {},
      object_storage_data: {},
      proxy_data: {},
      proxy_config: {},
      backup_work: {},
    },
    secrets: {
      internal_ca_certificate: secretFile('internal_ca_certificate'),
      registration_invite_secret: secretFile('registration_invite_secret'),
      postgres_superuser_password: secretFile('postgres_superuser_password'),
      postgres_tls_certificate: secretFile('postgres_tls_certificate'),
      postgres_tls_key: secretFile('postgres_tls_key'),
      storage_identities: secretFile('storage_identities'),
      storage_tls_certificate: secretFile('storage_tls_certificate'),
      storage_tls_key: secretFile('storage_tls_key'),
      backup_pg_service: secretFile('backup_pg_service'),
      storage_backup_access_key: secretFile('storage_backup_access_key'),
      storage_backup_secret_key: secretFile('storage_backup_secret_key'),
      backup_age_recipient: secretFile('backup_age_recipient'),
    },
  };
  return `${JSON.stringify(override, null, 2)}\n`;
}

/**
 * The proxy keeps one private key for the certificate across renewals: the
 * desktop and Android apps pin its hash. The setup places that key in the
 * proxy's storage before the first certificate is requested.
 */
export function renderCaddyfile(settings: Settings): string {
  const local = settings.certificates === 'local';
  const globals = [
    ...(settings.acmeEmail ? [`\temail ${settings.acmeEmail}`] : []),
    // The local authority's root stays in the proxy's storage instead of this host's trust store.
    ...(local ? ['\tskip_install_trust'] : []),
  ];
  return [
    `# ${GENERATED_HEADER}`,
    ...(globals.length > 0 ? ['{', ...globals, '}', ''] : []),
    `${settings.domain} {`,
    `\t${local ? 'tls internal {' : 'tls {'}`,
    '\t\tkey_type p256',
    '\t\treuse_private_keys',
    '\t}',
    '',
    '\t# Health checks and metrics stay on this host.',
    '\t@private path /health /health/* /metrics /metrics/*',
    '\trespond @private 404',
    '',
    '\t# The app expects whole request bodies (up to 2 MiB of JSON) before it reads them.',
    '\treverse_proxy app:3000 {',
    '\t\trequest_buffers 4MiB',
    '\t}',
    '}',
    '',
  ].join('\n');
}

export function renderPgHba(): string {
  return [
    `# ${GENERATED_HEADER}`,
    '# The superuser only through the local socket; the three roles only over TLS with a password.',
    'local   all     postgres  peer',
    `hostssl ${DATABASE.name} ${DATABASE.owner},${DATABASE.app},${DATABASE.backup} all scram-sha-256`,
    '',
  ].join('\n');
}

/** A path or argument for an ExecStart line: quoted, with systemd's specifier and variable characters escaped. */
function systemdArgument(value: string): string {
  return `"${value.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/%/g, '%%').replace(/\$/g, '$$$$')}"`;
}

export const BACKUP_UNIT = `${PROJECT_NAME}-backup`;

export function renderBackupUnits(settings: Settings, paths: Paths, nodePath: string): { service: string; timer: string } {
  if (!settings.backup) throw new Error('Backups are not configured');
  const main = join(paths.repo, 'setup', 'src', 'main.ts');
  const service = [
    `# ${GENERATED_HEADER}`,
    '[Unit]',
    'Description=Encrypted backup of the Alparts server',
    'Wants=docker.service',
    'After=docker.service network-online.target',
    '',
    '[Service]',
    'Type=oneshot',
    `ExecStart=${systemdArgument(nodePath)} ${systemdArgument(main)} backup --scheduled --lang ${settings.language}`,
    'TimeoutStartSec=6h',
    'Nice=10',
    'IOSchedulingClass=best-effort',
    'IOSchedulingPriority=7',
    '',
  ].join('\n');
  const timer = [
    `# ${GENERATED_HEADER}`,
    '[Unit]',
    'Description=Daily encrypted backup of the Alparts server',
    '',
    '[Timer]',
    `OnCalendar=*-*-* ${settings.backup.time}:00`,
    'RandomizedDelaySec=10m',
    'Persistent=true',
    'AccuracySec=1m',
    '',
    '[Install]',
    'WantedBy=timers.target',
    '',
  ].join('\n');
  return { service, timer };
}
